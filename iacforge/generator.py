"""Terraform generation from a validated, normalised spec.

The output is plain `aws_*` resources (no external modules), so `terraform init`
only needs the AWS provider.
"""

from __future__ import annotations

import ipaddress
import json
from pathlib import Path

from .spec import DB_PORTS

HEADER = "# Generated by iac-forge. Do not edit by hand: change the YAML spec and regenerate.\n\n"
ALL_TRAFFIC_V4 = '["0.0.0.0/0"]'


# ------------------------------------------------------------------ HCL helpers


def q(value) -> str:
    """Quote user-supplied text as an HCL string (and neutralise interpolation)."""
    return json.dumps(str(value)).replace("${", "$${")


def b(value: bool) -> str:
    return "true" if value else "false"


def ident(name: str) -> str:
    return name.replace("-", "_")


def hcl_list(values) -> str:
    return "[" + ", ".join(q(v) for v in values) + "]"


def attrs(items, indent: int = 1) -> str:
    """`key = value` lines with aligned equals signs, like `terraform fmt`."""
    pad = "  " * indent
    width = max(len(k) for k, _ in items)
    return "\n".join(f"{pad}{k.ljust(width)} = {v}" for k, v in items)


def nested(name: str, body: str, indent: int = 1) -> str:
    pad = "  " * indent
    return f"{pad}{name} {{\n{body}\n{pad}}}"


def map_attr(key: str, items, indent: int = 1) -> str:
    pad = "  " * indent
    return f"{pad}{key} = {{\n{attrs(items, indent + 1)}\n{pad}}}"


def block(header: str, parts) -> str:
    body = "\n\n".join(p for p in parts if p)
    return f"{header} {{\n{body}\n}}\n"


def resource(rtype: str, name: str, parts) -> str:
    return block(f'resource "{rtype}" "{name}"', parts)


def name_tag(suffix: str, indexed: bool = False) -> str:
    label = f"${{local.name}}-{suffix}" + ("-${count.index + 1}" if indexed else "")
    return map_attr("tags", [("Name", f'"{label}"')])


# ------------------------------------------------------------------- generators


def gen_providers(spec: dict) -> str:
    tags = {"Project": spec["name"], "Environment": spec["environment"], "ManagedBy": "iac-forge"}
    tags.update({str(k): str(v) for k, v in spec["tags"].items()})
    default_tags = nested("default_tags", map_attr("tags", [(q(k), q(v)) for k, v in tags.items()], 2))
    return (
        "terraform {\n"
        '  required_version = ">= 1.5.0"\n\n'
        "  required_providers {\n"
        "    aws = {\n"
        '      source  = "hashicorp/aws"\n'
        '      version = "~> 5.0"\n'
        "    }\n"
        "  }\n"
        "}\n\n"
        + block("provider \"aws\"", [attrs([("region", q(spec["region"]))]), default_tags])
        + "\n"
        + block("locals", [attrs([("name", q(f"{spec['name']}-{spec['environment']}"))])])
        + "\n"
        + 'data "aws_caller_identity" "current" {}\n\n'
        + 'data "aws_availability_zones" "available" {\n  state = "available"\n}\n'
    )


def gen_network(spec: dict) -> str:
    cfg = spec["network"]
    net = ipaddress.ip_network(cfg["cidr"])
    n_pub, n_priv = cfg["public_subnets"], cfg["private_subnets"]
    blocks = list(net.subnets(prefixlen_diff=4))  # 16 equal slices; public first, private from slot 8
    pub = [str(c) for c in blocks[:n_pub]]
    priv = [str(c) for c in blocks[8 : 8 + n_priv]]

    out = [
        resource("aws_vpc", "main", [
            attrs([("cidr_block", q(cfg["cidr"])), ("enable_dns_support", "true"), ("enable_dns_hostnames", "true")]),
            name_tag("vpc"),
        ])
    ]

    cidr_locals = []
    if pub:
        cidr_locals.append(("public_subnet_cidrs", hcl_list(pub)))
    if priv:
        cidr_locals.append(("private_subnet_cidrs", hcl_list(priv)))
    if cidr_locals:
        out.append(block("locals", [attrs(cidr_locals)]))

    az = "element(data.aws_availability_zones.available.names, count.index)"

    if pub:
        out += [
            resource("aws_internet_gateway", "main", [attrs([("vpc_id", "aws_vpc.main.id")]), name_tag("igw")]),
            resource("aws_subnet", "public", [
                attrs([
                    ("count", str(n_pub)),
                    ("vpc_id", "aws_vpc.main.id"),
                    ("cidr_block", "local.public_subnet_cidrs[count.index]"),
                    ("availability_zone", az),
                    ("map_public_ip_on_launch", "true"),
                ]),
                name_tag("public", indexed=True),
            ]),
            resource("aws_route_table", "public", [
                attrs([("vpc_id", "aws_vpc.main.id")]),
                nested("route", attrs([("cidr_block", '"0.0.0.0/0"'), ("gateway_id", "aws_internet_gateway.main.id")], 2)),
                name_tag("public-rt"),
            ]),
            resource("aws_route_table_association", "public", [attrs([
                ("count", str(n_pub)),
                ("subnet_id", "aws_subnet.public[count.index].id"),
                ("route_table_id", "aws_route_table.public.id"),
            ])]),
        ]

    if priv:
        out.append(resource("aws_subnet", "private", [
            attrs([
                ("count", str(n_priv)),
                ("vpc_id", "aws_vpc.main.id"),
                ("cidr_block", "local.private_subnet_cidrs[count.index]"),
                ("availability_zone", az),
            ]),
            name_tag("private", indexed=True),
        ]))
        private_rt = [attrs([("vpc_id", "aws_vpc.main.id")])]
        if cfg["nat_gateway"]:
            out += [
                resource("aws_eip", "nat", [attrs([("domain", '"vpc"')]), name_tag("nat-eip")]),
                resource("aws_nat_gateway", "main", [
                    attrs([("allocation_id", "aws_eip.nat.id"), ("subnet_id", "aws_subnet.public[0].id")]),
                    name_tag("nat"),
                    attrs([("depends_on", "[aws_internet_gateway.main]")]),
                ]),
            ]
            private_rt.append(nested("route", attrs([("cidr_block", '"0.0.0.0/0"'), ("nat_gateway_id", "aws_nat_gateway.main.id")], 2)))
        private_rt.append(name_tag("private-rt"))
        out += [
            resource("aws_route_table", "private", private_rt),
            resource("aws_route_table_association", "private", [attrs([
                ("count", str(n_priv)),
                ("subnet_id", "aws_subnet.private[count.index].id"),
                ("route_table_id", "aws_route_table.private.id"),
            ])]),
        ]
    return "\n".join(out)


def _egress_all() -> str:
    return nested("egress", attrs([("from_port", "0"), ("to_port", "0"), ("protocol", '"-1"'), ("cidr_blocks", ALL_TRAFFIC_V4)], 2))


def _ingress(port: int, **source) -> str:
    items = [("from_port", str(port)), ("to_port", str(port)), ("protocol", '"tcp"')]
    items += list(source.items())
    return nested("ingress", attrs(items, 2))


def gen_security(spec: dict) -> str:
    lb, db = spec["loadbalancer"], spec["database"]
    out = []

    if lb:
        ports = [443, 80] if lb["listener"] == "https" else [80]
        out.append(resource("aws_security_group", "alb", [
            attrs([("name", '"${local.name}-alb-sg"'), ("description", '"Public entry point"'), ("vpc_id", "aws_vpc.main.id")]),
            *[_ingress(p, cidr_blocks=ALL_TRAFFIC_V4) for p in ports],
            _egress_all(),
            name_tag("alb-sg"),
        ]))

    app_sgs = []
    for inst in spec["instances"]:
        label = f"app_{ident(inst['name'])}"
        app_sgs.append(f"aws_security_group.{label}.id")
        rules = []
        if lb and lb["target"] == inst["name"]:
            rules.append(_ingress(inst["port"], security_groups="[aws_security_group.alb.id]"))
        if inst["ssh_cidr"]:
            rules.append(_ingress(22, cidr_blocks=hcl_list([inst["ssh_cidr"]])))
        out.append(resource("aws_security_group", label, [
            attrs([
                ("name", f'"${{local.name}}-{inst["name"]}-sg"'),
                ("description", q(f"Instance group {inst['name']}")),
                ("vpc_id", "aws_vpc.main.id"),
            ]),
            *rules,
            _egress_all(),
            name_tag(f"{inst['name']}-sg"),
        ]))

    if db:
        port = DB_PORTS[db["engine"]]
        source = {"security_groups": "[" + ", ".join(app_sgs) + "]"} if app_sgs else {"cidr_blocks": "[aws_vpc.main.cidr_block]"}
        out.append(resource("aws_security_group", "db", [
            attrs([("name", '"${local.name}-db-sg"'), ("description", '"Database access from the application tier"'), ("vpc_id", "aws_vpc.main.id")]),
            _ingress(port, **source),
            _egress_all(),
            name_tag("db-sg"),
        ]))
    return "\n".join(out)


def gen_compute(spec: dict) -> str:
    if not spec["instances"]:
        return ""
    out = [block('data "aws_ami" "al2023"', [
        attrs([("most_recent", "true"), ("owners", '["amazon"]')]),
        nested("filter", attrs([("name", '"name"'), ("values", '["al2023-ami-2023*-x86_64"]')], 2)),
    ])]
    for inst in spec["instances"]:
        label = ident(inst["name"])
        tier = inst["placement"]
        out.append(resource("aws_instance", label, [
            attrs([
                ("count", str(inst["count"])),
                ("ami", "data.aws_ami.al2023.id"),
                ("instance_type", q(inst["instance_type"])),
                ("subnet_id", f"element(aws_subnet.{tier}[*].id, count.index)"),
                ("vpc_security_group_ids", f"[aws_security_group.app_{label}.id]"),
            ]),
            nested("metadata_options", attrs([
                ("http_endpoint", '"enabled"'),
                ("http_tokens", q("required" if inst["imdsv2"] else "optional")),
                ("http_put_response_hop_limit", "1"),
            ], 2)),
            nested("root_block_device", attrs([
                ("volume_size", str(inst["root_volume_gb"])),
                ("volume_type", '"gp3"'),
                ("encrypted", "true"),
            ], 2)),
            name_tag(inst["name"], indexed=True),
        ]))
    return "\n".join(out)


def gen_database(spec: dict) -> str:
    db = spec["database"]
    if not db:
        return ""
    prod = spec["environment"] == "prod"
    main = [
        attrs([
            ("identifier", '"${local.name}-db"'),
            ("engine", q(db["engine"])),
            ("instance_class", q(db["instance_class"])),
            ("allocated_storage", str(db["storage_gb"])),
            ("storage_encrypted", b(db["encrypted"])),
            ("multi_az", b(db["multi_az"])),
            ("publicly_accessible", b(db["publicly_accessible"])),
            ("username", '"dbadmin"'),
            ("manage_master_user_password", "true"),
            ("db_subnet_group_name", "aws_db_subnet_group.main.name"),
            ("vpc_security_group_ids", "[aws_security_group.db.id]"),
            ("backup_retention_period", str(db["backup_retention_days"])),
            ("auto_minor_version_upgrade", "true"),
            ("deletion_protection", b(prod)),
            ("skip_final_snapshot", b(not prod)),
        ]),
    ]
    if prod:
        main.append(attrs([("final_snapshot_identifier", '"${local.name}-db-final"')]))
    main.append(name_tag("db"))
    return "\n".join([
        resource("aws_db_subnet_group", "main", [
            attrs([("name", '"${local.name}-db"'), ("subnet_ids", "aws_subnet.private[*].id")]),
            name_tag("db-subnets"),
        ]),
        resource("aws_db_instance", "main", main),
    ])


def gen_storage(spec: dict) -> str:
    out = []
    for bucket in spec["buckets"]:
        label = ident(bucket["name"])
        out.append(resource("aws_s3_bucket", label, [
            attrs([("bucket", f'"${{local.name}}-{bucket["name"]}-${{data.aws_caller_identity.current.account_id}}"')]),
        ]))
        if bucket["versioning"]:
            out.append(resource("aws_s3_bucket_versioning", label, [
                attrs([("bucket", f"aws_s3_bucket.{label}.id")]),
                nested("versioning_configuration", attrs([("status", '"Enabled"')], 2)),
            ]))
        if bucket["encryption"]:
            out.append(resource("aws_s3_bucket_server_side_encryption_configuration", label, [
                attrs([("bucket", f"aws_s3_bucket.{label}.id")]),
                nested("rule", nested("apply_server_side_encryption_by_default", attrs([("sse_algorithm", '"AES256"')], 3), 2)),
            ]))
        blocked = b(not bucket["public"])
        out.append(resource("aws_s3_bucket_public_access_block", label, [attrs([
            ("bucket", f"aws_s3_bucket.{label}.id"),
            ("block_public_acls", blocked),
            ("block_public_policy", blocked),
            ("ignore_public_acls", blocked),
            ("restrict_public_buckets", blocked),
        ])]))
    return "\n".join(out)


def gen_loadbalancer(spec: dict) -> str:
    lb = spec["loadbalancer"]
    if not lb:
        return ""
    target = next(i for i in spec["instances"] if i["name"] == lb["target"])
    label = ident(target["name"])
    forward = nested("default_action", attrs([("type", '"forward"'), ("target_group_arn", "aws_lb_target_group.main.arn")], 2))

    out = [
        resource("aws_lb", "main", [
            attrs([
                ("name", '"${local.name}-alb"'),
                ("load_balancer_type", '"application"'),
                ("internal", "false"),
                ("security_groups", "[aws_security_group.alb.id]"),
                ("subnets", "aws_subnet.public[*].id"),
            ]),
            name_tag("alb"),
        ]),
        resource("aws_lb_target_group", "main", [
            attrs([("name", '"${local.name}-tg"'), ("port", str(target["port"])), ("protocol", '"HTTP"'), ("vpc_id", "aws_vpc.main.id")]),
            nested("health_check", attrs([("path", q(lb["health_check_path"])), ("matcher", '"200-399"')], 2)),
        ]),
        resource("aws_lb_target_group_attachment", "main", [attrs([
            ("count", str(target["count"])),
            ("target_group_arn", "aws_lb_target_group.main.arn"),
            ("target_id", f"aws_instance.{label}[count.index].id"),
            ("port", str(target["port"])),
        ])]),
    ]
    if lb["listener"] == "https":
        redirect = nested("default_action", "\n".join([
            attrs([("type", '"redirect"')], 2),
            nested("redirect", attrs([("port", '"443"'), ("protocol", '"HTTPS"'), ("status_code", '"HTTP_301"')], 3), 2),
        ]))
        out += [
            resource("aws_lb_listener", "https", [
                attrs([
                    ("load_balancer_arn", "aws_lb.main.arn"),
                    ("port", "443"),
                    ("protocol", '"HTTPS"'),
                    ("ssl_policy", '"ELBSecurityPolicy-TLS13-1-2-2021-06"'),
                    ("certificate_arn", q(lb["certificate_arn"])),
                ]),
                forward,
            ]),
            resource("aws_lb_listener", "http_redirect", [
                attrs([("load_balancer_arn", "aws_lb.main.arn"), ("port", "80"), ("protocol", '"HTTP"')]),
                redirect,
            ]),
        ]
    else:
        out.append(resource("aws_lb_listener", "http", [
            attrs([("load_balancer_arn", "aws_lb.main.arn"), ("port", "80"), ("protocol", '"HTTP"')]),
            forward,
        ]))
    return "\n".join(out)


def gen_outputs(spec: dict) -> str:
    out = [block('output "vpc_id"', [attrs([("value", "aws_vpc.main.id")])])]
    if spec["loadbalancer"]:
        out.append(block('output "alb_dns_name"', [attrs([("value", "aws_lb.main.dns_name")])]))
    if spec["database"]:
        out.append(block('output "db_endpoint"', [attrs([("value", "aws_db_instance.main.endpoint")])]))
    for bucket in spec["buckets"]:
        out.append(block(f'output "bucket_{ident(bucket["name"])}"', [attrs([("value", f"aws_s3_bucket.{ident(bucket['name'])}.bucket")])]))
    return "\n".join(out)


GENERATORS = (
    ("providers.tf", gen_providers),
    ("network.tf", gen_network),
    ("security.tf", gen_security),
    ("compute.tf", gen_compute),
    ("database.tf", gen_database),
    ("storage.tf", gen_storage),
    ("loadbalancer.tf", gen_loadbalancer),
    ("outputs.tf", gen_outputs),
)


def generate(spec: dict) -> dict[str, str]:
    """Return {filename: terraform source}; files with nothing to say are omitted."""
    files = {}
    for filename, fn in GENERATORS:
        content = fn(spec)
        if content.strip():
            files[filename] = HEADER + content.rstrip("\n") + "\n"
    return files


def write_files(files: dict[str, str], outdir: str | Path) -> list[Path]:
    out = Path(outdir)
    out.mkdir(parents=True, exist_ok=True)
    written = []
    for filename, content in files.items():
        path = out / filename
        path.write_text(content, encoding="utf-8")
        written.append(path)
    return written
