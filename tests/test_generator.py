import copy
from pathlib import Path

import yaml

from iacforge.generator import generate, write_files
from iacforge.spec import normalize

ROOT = Path(__file__).resolve().parents[1]


def spec(name):
    return normalize(yaml.safe_load((ROOT / "examples" / name).read_text()))


def test_webapp_produces_every_file():
    files = generate(spec("webapp.yaml"))
    assert set(files) == {
        "providers.tf", "network.tf", "security.tf", "compute.tf",
        "database.tf", "storage.tf", "loadbalancer.tf", "outputs.tf",
    }


def test_dev_without_load_balancer_omits_that_file():
    files = generate(spec("api-dev.yaml"))
    assert "loadbalancer.tf" not in files
    assert "alb_dns_name" not in files["outputs.tf"]


def test_subnet_cidrs_are_carved_from_the_vpc_range():
    network = generate(spec("webapp.yaml"))["network.tf"]
    assert '["10.20.0.0/20", "10.20.16.0/20"]' in network  # public
    assert '["10.20.128.0/20", "10.20.144.0/20"]' in network  # private


def test_braces_and_quotes_are_balanced_in_every_file():
    for example in ("webapp.yaml", "api-dev.yaml"):
        for filename, content in generate(spec(example)).items():
            assert content.count("{") == content.count("}"), filename
            assert content.count('"') % 2 == 0, filename
            assert "None" not in content, filename
            assert "\t" not in content, filename


def test_https_listener_adds_redirect_and_certificate():
    lb = generate(spec("webapp.yaml"))["loadbalancer.tf"]
    assert '"ELBSecurityPolicy-TLS13-1-2-2021-06"' in lb
    assert "HTTP_301" in lb
    assert "arn:aws:acm:eu-west-3" in lb


def test_http_listener_forwards_directly():
    s = spec("webapp.yaml")
    s["loadbalancer"]["listener"] = "http"
    lb = generate(s)["loadbalancer.tf"]
    assert 'resource "aws_lb_listener" "http"' in lb
    assert "HTTPS" not in lb


def test_database_is_encrypted_with_managed_password():
    db = generate(spec("webapp.yaml"))["database.tf"]
    assert "storage_encrypted           = true" in db
    assert "manage_master_user_password = true" in db
    assert "deletion_protection         = true" in db  # prod


def test_dev_database_skips_final_snapshot():
    db = generate(spec("api-dev.yaml"))["database.tf"]
    assert "skip_final_snapshot         = true" in db
    assert "final_snapshot_identifier" not in db


def test_instances_enforce_imdsv2_and_encrypted_disks():
    compute = generate(spec("webapp.yaml"))["compute.tf"]
    assert '"required"' in compute
    assert "encrypted   = true" in compute


def test_nat_gateway_only_when_requested():
    s = copy.deepcopy(spec("webapp.yaml"))
    assert "aws_nat_gateway" in generate(s)["network.tf"]
    s["network"]["nat_gateway"] = False
    assert "aws_nat_gateway" not in generate(s)["network.tf"]


def test_user_text_cannot_inject_interpolation():
    s = spec("webapp.yaml")
    s["tags"]["owner"] = "${file(\"/etc/passwd\")}"
    assert "$${file" in generate(s)["providers.tf"]


def test_mysql_uses_port_3306():
    security = generate(spec("api-dev.yaml"))["security.tf"]
    assert "3306" in security


def test_s3_buckets_block_public_access():
    storage = generate(spec("webapp.yaml"))["storage.tf"]
    assert "block_public_acls       = true" in storage


def test_write_files(tmp_path):
    files = generate(spec("webapp.yaml"))
    written = write_files(files, tmp_path / "out")
    assert len(written) == len(files)
    assert all(p.read_text().startswith("# Generated by iac-forge") for p in written)
